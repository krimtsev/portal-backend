/**
 * Шаг 1. Получаем из БД всё, что «в работе» — открытые и не отключённые тарифы.
 */
$openTariffs = DB::table('yc_tariffs')
    ->whereNull('end_date')
    ->where('disabled', false)
    ->where('start_date', '<=', $closeDate)
    ->get(['service_id', 'cost']);

$openFilterPrices = []; // service_id => null
$openComplexPrices = []; // service_id => cost

foreach ($openTariffs as $row) {
    if ($row->cost === null) {
        $openFilterPrices[$row->service_id] = null;
    } else {
        $openComplexPrices[$row->service_id] = (float) $row->cost;
    }
}

/**
 * Шаг 2. Анализ по услугам БЕЗ цены.
 *  - старые, которых нет в новом списке → закрыть;
 *  - новые, которых нет в открытых → вставить.
 */
$filterToClose = array_values(array_diff(array_keys($openFilterPrices), array_keys($newFilterServices)));
$filterToInsert = array_values(array_diff(array_keys($newFilterServices), array_keys($openFilterPrices)));

/**
 * Шаг 3. Анализ по услугам С ценой.
 *  - новый id → вставить;
 *  - есть старый и новый:
 *      • цена изменилась → закрыть старый + вставить новый;
 *      • цена та же → оставить как есть;
 *  - есть только старый → закрыть.
 */
$complexToClose = []; // service_id, которые нужно закрыть
$complexPriceChange = []; // service_id, у которых цена изменилась
$complexToInsert = []; // service_id, которые нужно вставить (новые + изменившиеся)

$newComplexIds = array_keys($newComplexServices);
$oldComplexIds = array_keys($openComplexPrices);

// старые, которых нет в новом списке
foreach ($oldComplexIds as $serviceId) {
    if (!array_key_exists($serviceId, $newComplexServices)) {
        $complexToClose[] = $serviceId;
    }
}

// сравнение цен
foreach ($newComplexServices as $serviceId => $data) {
    if (!array_key_exists($serviceId, $openComplexPrices)) {
        // новый id
        $complexToInsert[] = $serviceId;

        continue;
    }

    $oldCost = (float) $openComplexPrices[$serviceId];
    $newCost = (float) $data['cost'];

    if (abs($oldCost - $newCost) > 0.00001) {
        // цена изменилась
        $complexPriceChange[] = $serviceId;
        $complexToClose[] = $serviceId;
        $complexToInsert[] = $serviceId;
    }
    // цена та же — ничего не делаем
}

$closedCount = 0;
$insertedCount = 0;
$priceChangedCount = count($complexPriceChange);

DB::transaction(function () use (
    $closeDate,
    $startDate,
    $now,
    $filterToClose,
    $filterToInsert,
    $newFilterServices,
    $complexToClose,
    $complexToInsert,
    $newComplexServices,
    &$closedCount,
    &$insertedCount
) {
    // 3.1. Старые БЕЗ цены, которых нет в новом списке → закрываем.
    if (!empty($filterToClose)) {
        $closedCount += DB::table('yc_tariffs')
            ->whereIn('service_id', $filterToClose)
            ->whereNull('cost')
            ->whereNull('end_date')
            ->where('start_date', '<=', $closeDate)
            ->update([
                'end_date'   => $closeDate,
                'updated_at' => $now,
            ]);
    }

    // 3.2. Старые С ценой, которые надо закрыть (нет в новом списке ИЛИ цена изменилась).
    if (!empty($complexToClose)) {
        $closedCount += DB::table('yc_tariffs')
            ->whereIn('service_id', $complexToClose)
            ->whereNotNull('cost')
            ->whereNull('end_date')
            ->where('start_date', '<=', $closeDate)
            ->update([
                'end_date'   => $closeDate,
                'updated_at' => $now,
            ]);
    }

    // 3.3. Новые БЕЗ цены → вставляем.
    foreach ($filterToInsert as $serviceId) {
        DB::table('yc_tariffs')->updateOrInsert(
            [
                'service_id' => $serviceId,
                'start_date' => $startDate,
            ],
            [
                'title'      => $newFilterServices[$serviceId],
                'cost'       => null,
                'end_date'   => null,
                'disabled'   => false,
                'created_at' => $now,
                'updated_at' => $now,
            ]
        );
        $insertedCount++;
    }

    // 3.4. Новые С ценой (новые id + изменившиеся цены) → вставляем.
    foreach ($complexToInsert as $serviceId) {
        $data = $newComplexServices[$serviceId];

        DB::table('yc_tariffs')->updateOrInsert(
            [
                'service_id' => $serviceId,
                'start_date' => $startDate,
            ],
            [
                'title'      => $data['title'],
                'cost'       => $data['cost'],
                'end_date'   => null,
                'disabled'   => false,
                'created_at' => $now,
                'updated_at' => $now,
            ]
        );
        $insertedCount++;
    }
});

